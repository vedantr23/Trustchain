/**
 * Main translation lookup
 */
export function t(lang: LangCode, key: string, fallback?: string): string {
  const current = translations[lang];
  if (current && current[key]) {
    return current[key];
  }
  const enVal = translations.en[key];
  if (enVal) {
    return enVal;
  }
  return fallback !== undefined ? fallback : key;
}

/**
 * Dynamic content translator (Categories, Urgencies, Statuses, Drive Titles, etc.)
 */
export function td(lang: LangCode, text?: string | number | null): string {
  if (text === undefined || text === null) return '';
  const str = String(text);
  if (lang === 'en') return str;

  // Exact match in dynamic dictionary
  if (dynamicDict[str] && dynamicDict[str][lang]) {
    return dynamicDict[str][lang];
  }

  // Check in main translation dictionary keys
  if (translations[lang] && translations[lang][str]) {
    return translations[lang][str];
  }

  return str;
}
